//! Small deterministic starting worlds; this is not a historical reconstruction.
use crate::{SimState, actions::Action, config::SimConfig, settlement::Path, spatial::Position};

/// An irregular coastal landscape with freely positioned settlement buildings.
pub fn coastal_outpost() -> SimState {
    let mut state = SimState::new(SimConfig {
        width: 48,
        height: 40,
        tick_dt: 0.1,
        ..SimConfig::default()
    });
    for z in 0..40 {
        for x in 0..48 {
            let dx = x as f32 - 24.;
            let dz = z as f32 - 20.;
            let radius = ((dx / 19.).powi(2) + (dz / 15.).powi(2)).sqrt();
            let undulation =
                (dx * 0.32 + dz * 0.18).sin() * 0.26 + (dz * 0.49 - dx * 0.15).cos() * 0.18;
            let c = state.grid.get_mut(x, z);
            c.elevation = (1.8 - radius.powi(3) * 2.4 + undulation).clamp(-2., 3.);
            c.fertility = 0.45;
            c.fungus = 0.35;
            c.plants = 0.45;
        }
    }
    state.subsurface = crate::subsurface::Subsurface::coastal(&state.grid, state.sea_level);
    state.step(0., &[]);
    let houses = [
        (20.3, 18.7, 0.2),
        (23.8, 17.6, -0.35),
        (27.2, 18.1, 0.4),
        (29.4, 21.8, -0.5),
        (24.7, 22.9, 0.12),
        (21.2, 23.2, -0.65),
    ];
    for (x, z, rotation) in houses {
        state.step(
            0.,
            &[Action::PlaceBuilding {
                position: Position::new(x, z),
                rotation,
            }],
        );
    }
    // Authored curved footpath. Stored as continuous world positions, ready for
    // later editing/routing; it is not generated by inhabitant traffic yet.
    let control = [
        Position::new(15., 22.),
        Position::new(21., 16.),
        Position::new(26., 25.),
        Position::new(33., 20.),
    ];
    let mut points = Vec::new();
    for i in 0..=96 {
        let t = i as f32 / 96.;
        let u = 1. - t;
        let at = |f: fn(Position) -> f32| {
            u.powi(3) * f(control[0])
                + 3. * u * u * t * f(control[1])
                + 3. * u * t * t * f(control[2])
                + t.powi(3) * f(control[3])
        };
        points.push(Position::new(at(|p| p.x), at(|p| p.z)));
    }
    if let Some(id) = state.path_ids.allocate() {
        state.paths.push(Path {
            id,
            points,
            width: crate::settlement::Building::PATH_WIDTH,
        });
    }
    state
}

/// Compact inhabited fixture; existing ecological fixture remains unpopulated.
pub fn living_settlement() -> SimState {
    let mut sim = SimState::new(crate::config::SimConfig {
        width: 16,
        height: 16,
        seed: 42,
        ..Default::default()
    });
    for c in sim.grid.cells_mut() {
        c.elevation = 1.;
    }
    for z in [7.6, 8.4] {
        for x in [7.5, 8., 8.5] {
            sim.step(
                0.,
                &[crate::actions::Action::PlaceBuilding {
                    position: crate::spatial::Position::new(x, z),
                    rotation: if z < 8. { 0. } else { std::f32::consts::PI },
                }],
            );
        }
    }
    crate::people::populate(&mut sim);
    sim
}
